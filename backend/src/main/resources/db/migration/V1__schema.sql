CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(160) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'WAREHOUSE', 'VIEWER'))
);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(40)    NOT NULL,
    name        VARCHAR(150)   NOT NULL,
    description VARCHAR(1000),
    category_id BIGINT         NOT NULL,
    cost        NUMERIC(12, 2) NOT NULL,
    price       NUMERIC(12, 2) NOT NULL,
    min_stock   INTEGER        NOT NULL DEFAULT 0,
    stock       INTEGER        NOT NULL DEFAULT 0,
    active      BOOLEAN        NOT NULL DEFAULT TRUE,
    version     BIGINT         NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_products_cost CHECK (cost >= 0),
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_min_stock CHECK (min_stock >= 0),
    -- Última línea de defensa: el stock nunca puede ser negativo.
    CONSTRAINT ck_products_stock CHECK (stock >= 0)
);

CREATE INDEX ix_products_category ON products (category_id);
CREATE INDEX ix_products_name ON products (name);

CREATE TABLE stock_movements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT       NOT NULL,
    type         VARCHAR(20)  NOT NULL,
    quantity     INTEGER      NOT NULL,
    delta        INTEGER      NOT NULL,
    stock_before INTEGER      NOT NULL,
    stock_after  INTEGER      NOT NULL,
    reason       VARCHAR(255),
    reference    VARCHAR(100),
    user_id      BIGINT       NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_movements_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_movements_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_movements_type CHECK (type IN ('IN', 'OUT', 'ADJUSTMENT')),
    CONSTRAINT ck_movements_quantity CHECK (quantity > 0),
    CONSTRAINT ck_movements_stock_after CHECK (stock_after >= 0)
);

CREATE INDEX ix_movements_product ON stock_movements (product_id, created_at);
CREATE INDEX ix_movements_created ON stock_movements (created_at);
